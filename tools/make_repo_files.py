"""Generate the four repository files for the public code artifact.

Why a script rather than four files typed out: requirements.txt must list what the code
actually imports, not what seemed likely. AGENTS.md section 4.8 forbids hard-writing derived
quantities, and a hand-written dependency list is exactly that -- it drifts from the code the
moment anyone adds an import. So this walks the source, collects top-level third-party module
names (stdlib and local packages excluded by a stdlib check plus a local-name check), and
writes what it finds.

The other three files are templates: README describes the code rather than restating the
paper's claims, .gitignore excludes the artifacts that must not be public (the submission is
under revision; third-party PDFs are copyrighted; the data caches exceed GitHub's file limit),
and CHANGELOG is distilled from the internal progress record with sensitive content removed.

Nothing is written outside the repository root.
"""
from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(r"D:\Deepseek Harness\smart-grid-security")
SRC = ROOT / "Rec-AD" / "code"

stdlib = set(sys.stdlib_module_names)

# Local package names, listed explicitly rather than harvested from the tree. Harvesting was
# the first attempt and it silently deleted torch and numpy from the output: rglob walks
# .venv-gpu, which contains thousands of .py files, and their stems entered the "local"
# set -- so the two most important dependencies were classified as first-party and dropped.
# An explicit list cannot fail that way, and adding a package here is a deliberate act.
local = {"recad", "data", "experiments", "baselines", "analysis"}
for d in SRC.iterdir():
    if d.is_dir() and not d.name.startswith(".") and (d / "__init__.py").exists():
        local.add(d.name)
# Top-level modules are first-party too. Without this, `evaluate` and `train` -- which are
# code/evaluate.py and code/train.py -- were listed as dependencies, because the directory
# scan above only catches packages. Only the top level is scanned: recursing is what broke
# the first attempt.
for f in SRC.glob("*.py"):
    local.add(f.stem)

third: dict[str, int] = {}
for py in SRC.rglob("*.py"):
    if any(part in {".venv", ".venv-gpu", "__pycache__"} for part in py.parts):
        continue
    try:
        tree = ast.parse(py.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        continue
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names = [a.name.split(".")[0] for a in node.names]
        elif isinstance(node, ast.ImportFrom):
            if node.level:          # relative import -> local
                continue
            names = [(node.module or "").split(".")[0]]
        else:
            continue
        for n in names:
            if n and n not in stdlib and n not in local:
                third[n] = third.get(n, 0) + 1

print("  third-party imports found (name: number of files):")
for n, c in sorted(third.items(), key=lambda kv: -kv[1]):
    print(f"    {n:20} {c}")

# Fail loudly if a dependency that the code cannot run without is absent. The first version
# of this script produced a plausible-looking file with no torch in it, and nothing in the
# output said so -- the omission only surfaced when the file was read. A missing dependency
# is not a formatting detail, so it is asserted rather than eyeballed.
for required in ("torch", "numpy"):
    if required not in third:
        print(f"  ABORT: {required} not found in any import; the extraction is broken")
        sys.exit(1)
print("  required dependencies present: torch, numpy")

# Optional / diagnostic-only modules that are not needed to reproduce the results.
# sklearn is deliberately NOT here: the random-forest baseline and the manifold test both
# use it, so it is required to reproduce two of the tables.
OPTIONAL = {"matplotlib", "seaborn", "tqdm", "pytest"}
core = sorted(n for n in third if n not in OPTIONAL)
extra = sorted(n for n in third if n in OPTIONAL)

REQ = ["# Generated by tools/make_repo_files.py from the imports actually present in the",
       "# source. Do not edit by hand: regenerate so the list cannot drift from the code.",
       "#",
       "# Versions are unpinned on purpose. The reported numbers were produced with the",
       "# versions recorded in the run metadata; pinning here would imply a guarantee this",
       "# artifact does not make.",
       ""]
REQ += core
REQ += ["", "# Plotting and diagnostics only; not needed to reproduce the tables."]
REQ += extra
(SRC / "requirements.txt").write_text("\n".join(REQ) + "\n", encoding="utf-8")
print(f"  wrote {SRC / 'requirements.txt'}  ({len(core)} core + {len(extra)} optional)")

